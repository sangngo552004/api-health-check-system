package com.example.apihealthchecksystem.domain.valueobject;

public enum ComparisonOperator {
  /** Lớn hơn (Greater Than) */
  GT,

  /** Lớn hơn hoặc bằng (Greater Than or Equal) */
  GTE,

  /** Nhỏ hơn (Less Than) */
  LT,

  /** Nhỏ hơn hoặc bằng (Less Than or Equal) */
  LTE,

  /** Bằng (Equals) */
  EQ,

  /** Khác (Not Equals) */
  NE
}
